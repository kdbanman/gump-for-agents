#!/usr/bin/env python3
"""ref-dice: the one-layer dice surrogate built FROM reference/oracle.py ALONE (offsets and rule), not from
research/blast/rigour/{geom,dense}.py nor from the dice agent's scripts.

A face is a set of gump cells in one {111} layer s = x + y + z (doubled coordinates), with an equivalence
`rep(q)` that maps a point of the layer to the face cell it stands for (None if it is not a cell of the face:
the free rim). The coins of cell p are its neighbours q with s(q) = s(p) - 2 (density rho1) and s(q) = s(p) - 4
(density rho2) that exist (on the hull: lie in the octahedron |x|+|y|+|z| <= R; elsewhere: all).
Neighbours above the face (s(q) > s(p)) are dead.

    face(kind, args, cells)   -> dict(nb, m1, m2, cells)   (cells: the list of points, in the indexing to use)
    alive_prob(m1, m2, k, s)  -> Fraction                  (B45/S345 over Bin(m1, rho1) + Bin(m2, rho2) heads)
    kernel_row(F, x)          -> list of 2^A Fractions     (product over cells)

The torus (H,K),(0,D): the layer s = 1 modulo the lattice generated by H*E1 + K*E2 and D*E2, E1 = (2,-2,0),
E2 = (2,0,-2). The strip W x D: modulo D*E2 only; a neighbour not equivalent to a cell is dead. The patch: no
identification. The hull R: cells with x, y, z >= 0, x + y + z = R (= the cells of the octahedron's (1,1,1) face).
"""
import os, sys, itertools
from fractions import Fraction
from math import comb

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '..', '..', 'reference'))
import oracle  # noqa: E402

R1, R2 = Fraction(11, 25), Fraction(21, 50)
E1, E2 = (2, -2, 0), (2, 0, -2)


def is_cell(p):
    return sum(c % 2 for c in p) == 1


def axis(p):
    return [c % 2 for c in p].index(1)


def nbrs(p):
    return [tuple(p[t] + o[t] for t in range(3)) for o in oracle.offsets(axis(p))]


def s(p):
    return p[0] + p[1] + p[2]


def ab(v):
    """(a, b) with v = a*E1 + b*E2 for a vector v of the plane s = 0 with even coordinates."""
    assert s(v) == 0 and all(c % 2 == 0 for c in v), v
    a, b = -v[1] // 2, -v[2] // 2
    assert (2 * a + 2 * b, -2 * a, -2 * b) == tuple(v)
    return a, b


def in_lattice(v, gens):
    """v (in (a,b) coordinates) in the integer span of the 1 or 2 generators (in (a,b) coordinates)?"""
    a, b = v
    if len(gens) == 0:
        return a == 0 and b == 0
    if len(gens) == 1:
        (g1, g2), = gens
        # v = n*g
        if g1 == 0:
            return a == 0 and b % g2 == 0
        return a % g1 == 0 and b == (a // g1) * g2
    (h, k), (z, d) = gens
    assert z == 0
    if a % h:
        return False
    m = a // h
    return (b - m * k) % d == 0


def build(kind, args, cells):
    """cells: list of points (the indexing). Returns nb (lists of indices, with multiplicity), m1, m2."""
    cells = [tuple(c) for c in cells]
    assert all(is_cell(c) for c in cells)
    if kind == 'hull':
        R, = args
        hullpt = lambda q: abs(q[0]) + abs(q[1]) + abs(q[2]) <= R
        mine = sorted(p for p in itertools.product(range(-R, R + 1), repeat=3)
                      if is_cell(p) and hullpt(p) and s(p) == R)
        assert sorted(cells) == mine, 'hull cells differ'

        def rep(q):
            return cells.index(q) if q in cells else None
        exists = hullpt
    else:
        if kind == 'torus':
            H, K, D = args
            gens = [(H, K), (0, D)]
            ncell = 3 * H * D
        elif kind == 'strip':
            W, D = args
            gens = [(0, D)]
            ncell = 3 * W * D
        elif kind == 'patch':
            W, D = args
            gens = []
            ncell = 3 * W * D
        assert len(cells) == ncell and all(s(c) == 1 for c in cells)
        # distinct classes
        for i, p in enumerate(cells):
            for j, q in enumerate(cells[:i]):
                if axis(p) == axis(q):
                    assert not in_lattice(ab(tuple(p[t] - q[t] for t in range(3))), gens), ('same class', p, q)

        def rep(q):
            hits = [j for j, p in enumerate(cells) if axis(p) == axis(q)
                    and in_lattice(ab(tuple(q[t] - p[t] for t in range(3))), gens)]
            assert len(hits) <= 1
            return hits[0] if hits else None
        exists = lambda q: True
        if kind == 'torus':   # every point of the layer is a cell of the face
            pass
    nb, m1, m2 = [], [], []
    for p in cells:
        lst, c1, c2 = [], 0, 0
        for q in nbrs(p):
            ds = s(q) - s(p)
            if ds == 0:
                r = rep(q)
                if r is not None:
                    lst.append(r)
            elif ds == -2:
                c1 += exists(q)
            elif ds == -4:
                c2 += exists(q)
            else:
                assert ds in (2, 4)
        nb.append(lst); m1.append(c1); m2.append(c2)
    return dict(nb=nb, m1=m1, m2=m2, cells=cells, A=len(cells))


def rule(alive, n):
    return n in (oracle.SURVIVE if alive else oracle.BIRTH)


def binp(m, r, j):
    return comb(m, j) * r ** j * (1 - r) ** (m - j)


def alive_prob(m1, m2, k, alive, r1=R1, r2=R2):
    return sum((binp(m1, r1, j) * binp(m2, r2, l) for j in range(m1 + 1) for l in range(m2 + 1)
                if rule(alive, k + j + l)), Fraction(0))


def a_table(F, r1=R1, r2=R2):
    """a[x][i] = P(cell i alive next | x)."""
    A = F['A']
    cache = {}
    out = []
    for x in range(2 ** A):
        row = []
        for i in range(A):
            k = sum((x >> j) & 1 for j in F['nb'][i])
            key = (F['m1'][i], F['m2'][i], k, (x >> i) & 1)
            if key not in cache:
                cache[key] = alive_prob(*key, r1=r1, r2=r2)
            row.append(cache[key])
        out.append(row)
    return out


def kernel_row(a_row, A):
    out = []
    for y in range(2 ** A):
        v = Fraction(1)
        for i in range(A):
            v *= a_row[i] if (y >> i) & 1 else 1 - a_row[i]
        out.append(v)
    return out

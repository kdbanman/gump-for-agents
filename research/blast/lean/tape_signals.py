#!/usr/bin/env python3
"""Writes Gump/TapeSignalsData.lean: the plain rake train of the line (research/signals/README.md section 30; the
frame of objects/line-C.json) at its four phases, and the nine signals that ride it rigidly (the push's E, U, H, K0
of section 30, `prove_echo.py`; the review's K3, N1, N2, N3, N4 of `research/audit/signals6/sig6.py`), and checks
each claim the Lean file proves against reference/oracle.py.

    python3 research/blast/lean/tape_signals.py > research/blast/lean/Gump/TapeSignalsData.lean

The train at generation 0 is rake5 on the even units and rakef on the odd units (line-C.json); its phase t holds on
unit u the cells BASE[t][u % 2] moved u units. Here BASE is computed with the oracle from a piece of 80 units
(read on units 0, 1, which the ends cannot reach in 4 generations). A signal of kind K with lowest unit u (of the
kind's parity) is the set of cells sig(K, u) flipped at train phase 1; the claim (Gump.Tape.Signals) is that
train(1) xor sig(K, u), after 2n generations, is train(1 + 2n) xor sig(K, u + dir * n).
Oracle checks here: (A) BASE has period exactly 4 and train(t + 2) is train(t) moved one unit towards -v;
(B) for each kind, 2n generations for n = 1 .. 12 on a piece of 100 units, compared on the units the ends cannot
reach; (C) the kinds and cells are those of sig6.py (read from that file's text).
"""
import re, sys
from tape_lib import load, orbit, tr, unit, units, shift, lean_list, ROOT

lc = load('research/signals/objects/line-C.json')
R5 = [tuple(c) for c in lc['rake5']]
RF = [tuple(c) for c in lc['rakef']]

SIGS = {
    'E': (0, [(1, 2, 2), (2, 0, 1), (2, 0, 3)], +1),
    'U': (1, [(0, 0, 3)], +1),
    'H': (1, [(1, 2, 2)], -1),
    'K0': (0, [(0, 0, 3)], -1),
    'K3': (0, [(0, 0, 3), (4, 0, 1)], -1),
    'N1': (0, [(0, 0, 1), (1, 2, 2), (2, 0, 3)], +1),
    'N2': (0, [(0, 0, 3), (2, 0, 1), (2, 0, 3), (4, 0, 1)], -1),
    'N3': (0, [(0, 0, 3), (2, 0, 1), (2, 0, 3), (4, 0, -1)], -1),
    'N4': (1, [(0, 0, 3), (1, 2, 2), (1, 2, 4)], -1),
}
ok = True


def report(name, good):
    global ok
    ok &= bool(good)
    print(('PASS ' if good else 'FAIL ') + name, file=sys.stderr, flush=True)


# (C) the table above is sig6.py's
src = open(f'{ROOT}/research/audit/signals6/sig6.py').read()
for k, (par, cells, d) in SIGS.items():
    m = re.search(rf"'{k}': \((\d), \[(.*?)\], ([+-]1)\)", src)
    theirs = (int(m.group(1)), sorted(tuple(int(v) for v in t) for t in re.findall(r'\((-?\d+), (-?\d+), (-?\d+)\)', m.group(2))), int(m.group(3)))
    report(f'C  {k}: parity, cells and direction as in research/audit/signals6/sig6.py', theirs == (par, sorted(cells), d))

piece0 = frozenset(tr(c, u) for u in range(-40, 40) for c in (R5 if u % 2 == 0 else RF))
orb = orbit(piece0, 6)
BASE = [[frozenset(tr(c, -par) for c in units(orb[t], par, par)) for par in (0, 1)] for t in range(6)]
report('A  the train has period exactly 4 (phases 0..3 distinct, phase 4 = phase 0)',
       BASE[4] == BASE[0] and BASE[5] == BASE[1] and len({tuple(map(frozenset, b)) for b in BASE[:4]}) == 4)
report('A  train(t + 2) on unit u = train(t) on unit u + 1, for every phase',
       all(BASE[(t + 2) % 4][par] == BASE[t][1 - par] for t in range(4) for par in (0, 1)))


def train(t, a, b):
    return frozenset(tr(c, u) for u in range(a, b) for c in BASE[t % 4][u % 2])


def sig(k, u):
    return frozenset(tr(c, u) for c in SIGS[k][1])


for k, (par, cells, d) in SIGS.items():
    u0 = par + 10 * 2
    s0 = train(1, -50, 50) ^ sig(k, u0)
    o = orbit(s0, 24)
    good = all(units(o[2 * n], -50 + 2 * n + 1, 49 - 2 * n - 1) ==
               units(train(1 + 2 * n, -50, 50) ^ sig(k, u0 + d * n), -50 + 2 * n + 1, 49 - 2 * n - 1)
               for n in range(1, 13))
    report(f'B  {k}: after 2n generations, train(1 + 2n) xor the signal moved {d:+d}*n units (n = 1..12, oracle)', good)
if not ok:
    print('SOME CHECKS FAILED', file=sys.stderr)
    sys.exit(1)
print('ALL PASS', file=sys.stderr)

lines = ['/-', 'Generated by tape_signals.py (do not edit): the plain rake train of the line at its four phases (unit 0',
         'and unit 1 moved to unit 0) and the nine signals that ride it (README section 30; research/audit/signals6/sig6.py).',
         '-/', 'import Gump.TapeBase', '', 'namespace Gump.Tape.Signals', 'open Gump', '',
         '/-- The train at phase t (0 .. 3) on a unit of parity par (0, 1), moved to unit 0. -/',
         'def trainBase : Nat → Nat → List Pt']
for t in range(4):
    for par in (0, 1):
        lines.append(f'  | {t}, {par} => {lean_list(BASE[t][par])}')
lines.append('  | _, _ => []')
lines += ['', '/-- The nine signals: (parity of the lowest unit, cells at train phase 1 relative to it, direction). -/',
          'inductive Kind where', '  | E | U | H | K0 | K3 | N1 | N2 | N3 | N4', 'deriving DecidableEq, Repr', '',
          'def Kind.par : Kind → Int']
lines += [f'  | .{k} => {SIGS[k][0]}' for k in SIGS]
lines += ['', 'def Kind.dir : Kind → Int'] + [f'  | .{k} => {SIGS[k][2]}' for k in SIGS]
lines += ['', 'def Kind.cells : Kind → List Pt'] + [f'  | .{k} => {lean_list(SIGS[k][1])}' for k in SIGS]
lines += ['', 'end Gump.Tape.Signals']
print('\n'.join(lines))

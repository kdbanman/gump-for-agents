#!/usr/bin/env python3
"""Writes Gump/CallUnionData.lean for the call law's part (a) (Gump/CallUnion.lean): the interaction set Z of push 9's
call line and store wire (the cells whose closed neighbourhood meets both the wire's tube H_V and the line's
diagonal hull H_L), its closed neighbourhood NZ, and the line's state on NZ at generations 0 .. 43 (by
reference/oracle.py; the Lean file re-checks every one of them on the bit box of Gump/CallBox.lean).

    python3 research/blast/lean/tape_callunion.py > research/blast/lean/Gump/CallUnionData.lean

H_V = {1 <= x+y+z <= 5, -1 <= x-y+z <= 5}: wire B, wire C, the stretch letters and e1 = (1,2,0) of the crossing unit
lie in it, at every unit. H_L = {d.p <= C_d for the eight diagonals d}, C_d the largest d.p over the line and the two
CALL cells. Also checked here on the oracle: the line with the CALL is the line at rest at generation 42 and has
period 2 from there.
"""
import sys
from tape_lib import load, orbit_box, lean_list, ROOT
sys.path.insert(0, ROOT + '/reference')
import oracle

D9 = load('research/signals/push9/objects/call9.json')
LINE = frozenset(tuple(c) for c in D9['runs'][0]['extra'])
CALL = frozenset(tuple(c) for c in D9['runs'][0]['ops'][3][2])
L0 = LINE | CALL
diags = [(a, b, c) for a in (1, -1) for b in (1, -1) for c in (1, -1)]
CL = {d: max(d[0] * x + d[1] * y + d[2] * z for x, y, z in L0) for d in diags}


def inHL(q):
    return all(d[0] * q[0] + d[1] * q[1] + d[2] * q[2] <= CL[d] for d in diags)


def inHV(q):
    D1 = q[0] + q[1] + q[2]; D2 = q[0] - q[1] + q[2]
    return 1 <= D1 <= 5 and -1 <= D2 <= 5


def isCell(p):
    return sum(v % 2 for v in p) == 1


def axis(p):
    return [i for i in range(3) if p[i] % 2][0]


def N(p):
    return [p] + [tuple(p[i] + o[i] for i in range(3)) for o in oracle.offsets(axis(p))]


# the box the Lean proof derives for such cells (from |Delta(d.p)| <= 4 over a neighbour): x 64..76, y -1..7,
# x + z -4..4; enumerate it
Z = []
for x in range(64, 77):
    for y in range(-1, 8):
        for z in range(-4 - x, 5 - x):
            p = (x, y, z)
            if isCell(p) and any(inHL(q) for q in N(p)) and any(inHV(q) for q in N(p)):
                Z.append(p)
NZ = sorted({q for p in Z for q in N(p)})
o = orbit_box(L0, 45)
assert o[42] == LINE and o[44] == LINE and o[45] == o[43], 'the line at rest from 42, period 2'
snaps = [sorted(q for q in o[t] if q in set(NZ)) for t in range(44)]
print(f'Z: {len(Z)} cells; NZ: {len(NZ)} points; line at rest from 42 (oracle)', file=sys.stderr)
cl = ', '.join(f'{CL[d]}' for d in diags)
out = ['/-', 'Generated by tape_callunion.py (do not edit): the interaction set Z of push 9\'s call line and store wire,',
       'its closed neighbourhood NZ, and the line\'s state on NZ at generations 0 .. 43 (by reference/oracle.py; re-checked',
       'by the kernel in Gump/CallUnion.lean).', '-/', 'import Gump.TapeBase', '', 'namespace Gump.Call', 'open Gump', '',
       f'/-- The interaction set ({len(Z)} cells). -/', f'def zoneZ : List Pt := {lean_list(Z)}', '',
       f'/-- Its closed neighbourhood ({len(NZ)} points). -/', f'def zoneNZ : List Pt := {lean_list(NZ)}', '',
       '/-- The line with the CALL on NZ at generation t (t < 44). -/', 'def lineSnap : Nat → List Pt']
for t in range(44):
    out.append(f'  | {t} => {lean_list(snaps[t])}')
out += ['  | _ => []', '', 'end Gump.Call']
print('\n'.join(out))

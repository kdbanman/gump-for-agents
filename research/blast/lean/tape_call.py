#!/usr/bin/env python3
"""Writes Gump/CallData.lean: the cells of push 9's call line (research/signals/push9/objects/call9.json, run 0:
'extra', 162 cells, the line at rest at an even generation) and the two cells of the CALL (run 0, ops[3]), as
research/audit/signals9/a9.py reads them, and checks that the unit alphabet (stators, sites) of push 8 and push 9 is
the one Gump/Unzip.lean uses.

    python3 research/blast/lean/tape_call.py > research/blast/lean/Gump/CallData.lean

Oracle checks (reference/oracle.py), which the Lean statements rest on as definitions, not as theorems:
  the line alone at rest has period 2;  the crossing unit is 4 + crossings[0] = 35;
  the hex units 7 and b are the units B and C of Gump/Tape.lean.
"""
import re, sys
from tape_lib import load, orbit, lean_list, HERE

D8 = load('research/signals/push8/objects/cell8.json')
D9 = load('research/signals/push9/objects/call9.json')
ST = [(0, 1, 2), (0, 1, 4)]
SI = [(1, 0, 0), (1, 0, 2), (1, 0, 4), (0, 2, 3)]
for D in (D8, D9):
    assert [tuple(c) for c in D['stators']] == ST and [tuple(c) for c in D['sites']] == SI
LINE = sorted({tuple(c) for c in D9['runs'][0]['extra']})
CALL = [tuple(c) for c in D9['runs'][0]['ops'][3][2]]
CROSS = 4 + D9['runs'][0]['crossings'][0]
assert len(LINE) == 162 and len(CALL) == 2 and CROSS == 35
hexu = lambda h: sorted(set(ST) | {SI[j] for j in range(4) if h >> j & 1})
src = open(f'{HERE}/Gump/Tape.lean').read()
for L, h in (('C', 11), ('B', 7)):
    m = re.search(rf'\| \.{L} => (\[.*?\])', src).group(1)
    assert sorted(tuple(int(v) for v in t) for t in re.findall(r'⟨(-?\d+), (-?\d+), (-?\d+)⟩', m)) == hexu(h), L
o = orbit(LINE, 2)
assert o[2] == o[0] and o[1] != o[0], 'the line at rest has period 2'
print('ALL PASS (line at rest: period 2; alphabet as in Tape.lean)', file=sys.stderr)
print(f'''/-
Generated by tape_call.py (do not edit): push 9's call line (research/signals/push9/objects/call9.json, run 0,
'extra': the line at rest at an even generation, {len(LINE)} cells), the two cells of the CALL (run 0, ops[3]), and the
crossing unit 4 + crossings[0] = {CROSS}, as research/audit/signals9/a9.py reads them.
-/
import Gump.TapeBase

namespace Gump.Call
open Gump

/-- The call line at rest ({len(LINE)} cells). -/
def line : List Pt := {lean_list(LINE)}

/-- The two cells of the CALL, made live at generation 0. -/
def callCells : List Pt := {lean_list(CALL)}

/-- The store unit the line crosses. -/
def cross : Int := {CROSS}

end Gump.Call''')

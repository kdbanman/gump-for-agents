#!/usr/bin/env python3
"""Writes Gump/CallReaderData.lean: the left cap of push 9's call line (research/signals/push9/objects/call9.json,
`capL`, on the units 0 .. 3, the store wire from unit 4 on), unit by unit, each unit moved to unit 0, and checks with
reference/oracle.py the fact Gump/CallReader.lean proves for every word: capL + any word over {B, C} on the units
>= 4 is, two generations later, capL + the word moved one unit (here for all 2^7 words on the units 4 .. 10,
compared on the units <= 8; the same test for the clock's capL on the units 0 .. 6).

    python3 research/blast/lean/tape_reader.py > research/blast/lean/Gump/CallReaderData.lean
"""
import sys, itertools
from tape_lib import load, orbit, tr, unit, units, lean_list

cap = [tuple(c) for c in load('research/signals/push9/objects/call9.json')['capL']]
capC = [tuple(c) for c in load('research/signals/objects/clock-C.json')['capL']]
ST = [(0, 1, 2), (0, 1, 4)]; SI = [(1, 0, 0), (1, 0, 2), (1, 0, 4), (0, 2, 3)]
hexc = lambda h: set(ST) | {SI[j] for j in range(4) if h >> j & 1}
LET = {'B': 7, 'C': 11}


def eats(cap, base, n=7):
    for w in itertools.product('BC', repeat=n):
        word = ''.join(w) + 'C' * 6
        s = set(cap)
        for i, ch in enumerate(word):
            s |= {tr(c, base + i) for c in hexc(LET[ch])}
        t = set(cap)
        for i, ch in enumerate(word[1:]):
            t |= {tr(c, base + i) for c in hexc(LET[ch])}
        hi = base + n - 3
        if units(orbit(s, 2)[2], -99, hi) != units(frozenset(t), -99, hi):
            return False
    return True


ok = True
for name, c, base in (('call9 capL', cap, 4), ('clock-C capL', capC, 0)):
    good = eats(c, base)
    ok &= good
    print(('PASS ' if good else 'FAIL ') + f'{name}: every word on 7 units, two generations: the cap and the word moved',
          file=sys.stderr, flush=True)
U = {u: sorted(tr(c, -u) for c in cap if unit(c) == u) for u in range(0, 4)}
assert sum(len(v) for v in U.values()) == len(cap)
if not ok:
    sys.exit(1)
print('''/-
Generated by tape_reader.py (do not edit): the left cap of push 9's call line (call9.json `capL`, units 0 .. 3), and
the same cap unit by unit moved four units towards -v (units -4 .. -1), each unit moved to unit 0.
-/
import Gump.TapeBase

namespace Gump.Reader
open Gump
''')
print(f'/-- call9.json `capL`, as given (units 0 .. 3). -/\ndef capL9 : List Pt := {lean_list(cap)}\n')
print('/-- Its unit 4 + u (u = -4 .. -1), moved to unit 0. -/\ndef cap9U : Int → List Pt')
for u in range(0, 4):
    print(f'  | {u - 4} => {lean_list(U[u])}')
print('  | _ => []\n\nend Gump.Reader')

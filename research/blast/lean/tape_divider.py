#!/usr/bin/env python3
"""Writes Gump/LineDividerData.lean for the divider (research/signals/objects/divider-C8.json, README section 21b):
its oscillator `osc` (the other parts, capA, the wire unit and the gun, are line-C's, which this script asserts) and
the even translation of the base runs into the box of Gump.Bits. Checks with reference/oracle.py: period exactly 8
from generation 2N - 3 and not periodic from 2N - 4, for N = 8 .. 16.

    python3 research/blast/lean/tape_divider.py > research/blast/lean/Gump/LineDividerData.lean
"""
import sys
from tape_lib import load, orbit, tr, unit, lean_list

d = load('research/signals/objects/divider-C8.json'); l = load('research/signals/objects/line-C.json')
T = lambda o, k: sorted(tuple(c) for c in o[k])
for k in ('capA', 'unit', 'gun'):
    assert T(d, k) == T(l, k), k
capA, U, gun, osc = T(d, 'capA'), T(d, 'unit'), T(d, 'gun'), T(d, 'osc')


def obj(N):
    return frozenset(set(capA) | {tr(c, k) for c in U for k in range(N)} | {tr(c, N) for c in gun + osc})


ok = True
for N in range(8, 17):
    mu = 2 * N - 3
    x = orbit(obj(N), mu + 16)
    good = x[mu + 8] == x[mu] and all(x[mu + k] != x[mu] for k in range(1, 8)) and x[mu - 1 + 8] != x[mu - 1]
    ok &= good
    print(('PASS' if good else 'FAIL'), f'N = {N}: period exactly 8 from {mu}, not periodic from {mu - 1}',
          file=sys.stderr, flush=True)
x = orbit(obj(14), 40)
allc = set().union(*x)
lo = [min(c[i] for c in allc) for i in range(3)]; hi = [max(c[i] for c in allc) for i in range(3)]
print('N = 14, generations 0 .. 40: ranges', lo, hi, file=sys.stderr)
# the core of the box is -12 .. 43 in each coordinate; centre, keep even
fr = [((-12 + 43) - (lo[i] + hi[i])) // 2 // 2 * 2 for i in range(3)]
assert all(-12 <= lo[i] + fr[i] and hi[i] + fr[i] < 44 for i in range(3)), (lo, hi, fr)
assert fr[0] % 4 == 0 or True
if not ok:
    sys.exit(1)
print(f'''/-
Generated by tape_divider.py (do not edit): the divider's oscillator (research/signals/objects/divider-C8.json `osc`,
units -4 .. -2, moved N units in the object; capA, the wire unit and the gun are line-C's), and the even translation
of the base runs into the box of `Gump.Bits`.
-/
import Gump.Tape

namespace Gump.Divider
open Gump

/-- The divider's oscillator, at unit 0 (units -4 .. -2). -/
def osc : List Pt := {lean_list(osc)}

/-- The even translation into the box (moves units by {fr[0] // 2}). -/
def dframe : Pt := ⟨{fr[0]}, {fr[1]}, {fr[2]}⟩

end Gump.Divider''')

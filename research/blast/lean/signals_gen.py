#!/usr/bin/env python3
"""Writes Gump/Signals.lean: line-C of research/signals/objects/line-C.json (a cap, N units of wire C and the rake gun,
free-standing) for the N stated there that fit the box of Gump/Bits.lean, as kernel-checked theorems: from generation
2N on the object is an oscillator of exact period 4 (the claim of research/NOTEBOOK.md, 2026-11-15, fourth signals push,
"from generation 2N on the whole object has period exactly 4").

    python3 research/blast/lean/signals_gen.py > research/blast/lean/Gump/Signals.lean

Each object is translated by an even vector (a lattice symmetry, `Gump.run_act`) so that its orbit up to generation
2N + 4, computed here with reference/oracle.py, lies in the core [-12, 44)^3 of `Gump.Bits`; the certificate itself
re-checks that in the kernel, so the oracle run only chooses the translation.
"""
import json, os, sys
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..', '..', '..')
sys.path.insert(0, os.path.join(ROOT, 'reference'))
import oracle  # noqa: E402

lc = json.load(open(os.path.join(ROOT, 'research', 'signals', 'objects', 'line-C.json')))
tr = lambda c, k: (c[0] + 2 * k, c[1], c[2] - 2 * k)


def cells(N):
    return sorted({tuple(c) for c in lc['capA']} | {tr(c, k) for c in lc['unit'] for k in range(N)} |
                  {tr(c, N) for c in lc['gun']})


def orbit_box(cs, gens):
    c = np.array(cs)
    H = 2 * (int(np.abs(c).sum(1).max()) + 2 * gens) + 16
    H += H % 2
    off = H // 2 & ~1
    m = oracle.masks(H)
    h = np.zeros((H, H, H), np.int8)
    for x in c + off:
        h[tuple(x)] = 1
    lo, hi = c.min(0), c.max(0)
    for _ in range(gens):
        h = oracle.step(h, m)
        pts = np.argwhere(h == 1) - off
        if len(pts):
            lo, hi = np.minimum(lo, pts.min(0)), np.maximum(hi, pts.max(0))
    return lo, hi


out = ['/-', 'Generated by signals_gen.py (do not edit): line-C of research/signals/objects/line-C.json, a cap, N units of',
       'wire C and the rake gun, free-standing. From generation 2N on it is an oscillator of exact period 4,',
       'checked by the kernel on the bit-parallel stepper (`Gump.Bits.evCert_spec`). Each object is translated by the',
       'even vector shown (a lattice symmetry, `Gump.run_act`) to sit in the box of `Gump.Bits`.', '-/',
       'import Gump.Bits', 'open Gump', '', 'namespace Gump.Signals', '']
for N in lc['N']:
    cs = cells(N)
    lo, hi = orbit_box(cs, 2 * N + 4)
    centre = (lo + hi) // 2
    v = (16 - centre) & ~1                          # even translation, centre near 16
    if ((lo + v) < -12).any() or ((hi + v) >= 44).any():
        print(f'-- line-C with N = {N}: orbit extent {hi - lo + 1} does not fit the core; skipped', file=sys.stderr)
        continue
    pts = ', '.join(f'⟨{x + v[0]}, {y + v[1]}, {z + v[2]}⟩' for x, y, z in cs)
    out += [f'/-- line-C with N = {N} ({len(cs)} cells), translated by ({v[0]}, {v[1]}, {v[2]}). -/',
            f'def lineC_{N} : List Pt := [{pts}]', '',
            f'/-- **line-C, N = {N}: from generation {2 * N} on, an oscillator of exact period 4.** -/',
            f'theorem lineC_{N}_period_four : 0 < 4 ∧ run (lcfg lineC_{N}) ({2 * N} + 4) = run (lcfg lineC_{N}) {2 * N} ∧',
            f'    ∀ k, 0 < k → k < 4 → run (lcfg lineC_{N}) ({2 * N} + k) ≠ run (lcfg lineC_{N}) {2 * N} :=',
            f'  Bits.evCert_spec lineC_{N} {2 * N} 4 (by decide +kernel)', '']
out += ['end Gump.Signals']
print('\n'.join(out))

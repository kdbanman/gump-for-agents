#!/usr/bin/env python3
"""Writes Gump/LineBeamData.lean for the beam (research/signals/objects/beam-5f.json, README section 21) and checks
the unit-by-unit form of the object and the base facts of Gump/LineBeam.lean against reference/oracle.py.

    python3 research/blast/lean/tape_beam.py > research/blast/lean/Gump/LineBeamData.lean

Object(N) = left (units -3 .. -1) + b0 on the even and b1 on the odd units 0 .. N - 1 + R_even or R_odd (by the
parity of N, units 0 .. 2) moved N units (prove_beam.py's `obj`). Each part is written unit by unit, moved to unit 0.
Checked here: the unit form reassembles to Object(N) for N = 1 .. 30; Object(N) has period exactly 4 for
N = 1 .. 9 (the oracle); and S(8), S(9): for u = 4, 5 and t = 0 .. 3 X_N(t) on unit u - 2 moved two units is
X_N(t) on unit u. The Lean kernel checks the same facts again on its own stepper.
"""
import sys
from tape_lib import load, orbit, tr, unit, units, shift, lean_list

ob = load('research/signals/objects/beam-5f.json')
T = lambda key: [tuple(c) for c in ob[key]]
left, b0, b1, Re, Ro = T('left'), T('b0'), T('b1'), T('R_even'), T('R_odd')


def obj(N):
    cells = set(left) | {tr(c, N) for c in (Ro if N % 2 else Re)}
    for k in range(N):
        cells |= {tr(c, k) for c in (b1 if k % 2 else b0)}
    return frozenset(cells)


def byunit(cells, lo, hi):
    d = {u: sorted(tr(c, -u) for c in cells if unit(c) == u) for u in range(lo, hi + 1)}
    assert sum(len(v) for v in d.values()) == len(cells), 'a cell outside the units'
    return d


LU, EU, OU = byunit(left, -3, -1), byunit(Re, 0, 2), byunit(Ro, 0, 2)
assert {unit(c) for c in b0} == {0} and {unit(c) for c in b1} == {0}


def obj_units(N):
    s = set()
    for u in range(-3, 0):
        s |= {tr(c, u) for c in LU[u]}
    for u in range(N):
        s |= {tr(c, u) for c in (b1 if u % 2 else b0)}
    R = OU if N % 2 else EU
    for v in range(3):
        s |= {tr(c, N + v) for c in R[v]}
    return frozenset(s)


ok = True
def report(name, good):
    global ok
    ok &= bool(good)
    print(('PASS ' if good else 'FAIL ') + name, file=sys.stderr, flush=True)


report('the unit form is Object(N) for N = 1 .. 30', all(obj_units(N) == obj(N) for N in range(1, 31)))
X = {}
for N in range(1, 10):
    X[N] = orbit(obj(N), 4)
    report(f'N = {N}: X(4) = X(0), X(2) != X(0)', X[N][4] == X[N][0] and X[N][2] != X[N][0])
for N in (8, 9):
    report(f'S({N}): X(t) on unit u - 2 moved two units = X(t) on unit u, u = 4, 5, t = 0 .. 3',
           all(shift(units(X[N][t], u - 2, u - 2), 2) == units(X[N][t], u, u) for u in (4, 5) for t in range(4)))
if not ok:
    sys.exit(1)

print('''/-
Generated by tape_beam.py (do not edit): the beam of research/signals/objects/beam-5f.json unit by unit, each unit
moved to unit 0: the left end (the mirror gun) on the units -3 .. -1, the two train units b0 (even) and b1 (odd), the
right end (the absorber) for even and odd N on the units 0 .. 2 (moved N units in the object).
-/
import Gump.TapeBase

namespace Gump.Beam
open Gump
''')
print('/-- The left end on unit u (u = -3 .. -1), moved to unit 0. -/\ndef leftU : Int → List Pt')
for u in range(-3, 0):
    print(f'  | {u} => {lean_list(LU[u])}')
print('  | _ => []\n')
print(f'/-- The train unit on the even units. -/\ndef b0 : List Pt := {lean_list(sorted(b0))}\n')
print(f'/-- The train unit on the odd units. -/\ndef b1 : List Pt := {lean_list(sorted(b1))}\n')
for name, D, doc in (('evenU', EU, 'even'), ('oddU', OU, 'odd')):
    print(f'/-- The right end for {doc} N on unit v (v = 0 .. 2), moved to unit 0. -/\ndef {name} : Int → List Pt')
    for v in range(3):
        print(f'  | {v} => {lean_list(D[v])}')
    print('  | _ => []\n')
print('end Gump.Beam')

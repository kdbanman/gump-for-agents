#!/usr/bin/env python3
"""Writes Gump/LineData.lean (the cells of line-C: capA and the gun, from research/signals/objects/line-C.json) and
checks with reference/oracle.py every base fact the Lean proof of the gun's line (Gump/Line.lean) has the kernel
check, so that a disagreement between the Lean rule and the oracle would show here too.

    python3 research/blast/lean/tape_line.py            # checks, then prints LineData.lean to stdout
    python3 research/blast/lean/tape_line.py > research/blast/lean/Gump/LineData.lean

Object(N) = capA + N units of bare wire C + the gun moved N units (README section 21). The Lean induction
(S(N, m) -> S(N+1, m+1), from S(4, 1)) uses, for N = 4, m = 1, with X(t) the orbit and L(t) = X(t-2) (t >= 2),
L(t) = X(t) (t < 2):
  per   X(12) = X(8)                              (period 4 from 2N = 8)
  wit2  X(10) != X(8) on the units >= m + 1 = 2    (not period 2; seen right of the seam)
  wit3  X(11) != X(7) on the units <= 2            (not periodic from 2N - 1; seen left of the seam)
  win   X(t) moved one unit = L(t) on the units 1, 2, for t = 0 .. 13
  rest  X(2) = X(0) on the units <= 2
and, for N = 2, 3, directly: X(2N+4) = X(2N), X(2N+2) != X(2N), X(2N+3) != X(2N-1).
As a test the proof does not need: the orbit glued from the two charts is the oracle's orbit of Object(N) for
N = 5 .. 12 (README's P4).
"""
import re, sys
from tape_lib import load, orbit, tr, units, shift, lean_list, HERE

lc = load('research/signals/objects/line-C.json')
capA = [tuple(c) for c in lc['capA']]
U = [tuple(c) for c in lc['unit']]
G = [tuple(c) for c in lc['gun']]
V = (16, 16, 16)        # the even translation into the bit box of Gump.Bits (units move by 8)

# the unit of wire C in Lean (Gump/Tape.lean, cellsOf .C) must be the JSON's unit
tape_src = open(f'{HERE}/Gump/Tape.lean').read()
mC = re.search(r'\| \.C => (\[.*?\])', tape_src).group(1)
leanC = [tuple(int(v) for v in t) for t in re.findall(r'⟨(-?\d+), (-?\d+), (-?\d+)⟩', mC)]
assert sorted(leanC) == sorted(U), 'cellsOf .C differs from line-C.json unit'


def obj(N):
    return frozenset(capA) | {tr(c, k) for c in U for k in range(N)} | {tr(c, N) for c in G}


ok = True


def report(name, good):
    global ok
    ok &= bool(good)
    print(('PASS ' if good else 'FAIL ') + name, file=sys.stderr, flush=True)


assert all((c[0] >> 1) < 0 for c in capA) and all(0 <= (c[0] >> 1) for c in G)
for N in (2, 3):
    X = orbit(obj(N), 2 * N + 4)
    report(f'N = {N}: X({2*N+4}) = X({2*N}), X({2*N+2}) != X({2*N}), X({2*N+3}) != X({2*N-1})',
           X[2 * N + 4] == X[2 * N] and X[2 * N + 2] != X[2 * N] and X[2 * N + 3] != X[2 * N - 1])
N, m = 4, 1
X = orbit(obj(N), 16)
Xs = orbit(shift(obj(N), 1), 16)
L = lambda t: X[t - 2] if t >= 2 else X[t]
report('per   X(12) = X(8)', X[12] == X[8])
report('wit2  X(10) != X(8) on units >= 2', units(X[10], m + 1, 99) != units(X[8], m + 1, 99))
report('wit3  X(11) != X(7) on units <= 2', units(X[11], -99, m + 1) != units(X[7], -99, m + 1))
report('win   (X(t) moved one unit) = L(t) on units 1, 2, t = 0..13; computed as the orbit of the moved object',
       all(units(Xs[t], m, m + 1) == units(L(t), m, m + 1) and Xs[t] == shift(X[t], 1) for t in range(14)))
report('rest  X(2) = X(0) on units <= 2', units(X[2], -99, m + 1) == units(X[0], -99, m + 1))
# P4: the glued orbit is the oracle's orbit
Xprev, mm = X, m
for N2 in range(5, 13):
    XN = orbit(obj(N2), 2 * N2 + 8)
    Lp = lambda t: Xprev[t - 2] if t >= 2 else Xprev[t]
    Y = [units(Lp(t), -99, mm) | frozenset(c for c in shift(Xprev[t], 1) if (c[0] >> 1) > mm) for t in range(2 * N2 + 7)]
    report(f'P4    N = {N2}: glued orbit = oracle orbit, t = 0..{2 * N2 + 6}', all(Y[t] == XN[t] for t in range(2 * N2 + 7)))
    Xprev, mm = XN, mm + 1
if not ok:
    print('SOME CHECKS FAILED', file=sys.stderr)
    sys.exit(1)
print('ALL PASS', file=sys.stderr)

print(f'''/-
Generated by tape_line.py (do not edit): the cells of line-C (research/signals/objects/line-C.json), the cap at
rest capA (18 cells, units -4 .. -1) and the rake gun (15 cells, units 0 .. 2), in the coordinates of the file;
and the even translation that puts the base runs in the box of `Gump.Bits`.
-/
import Gump.Tape

namespace Gump.Line
open Gump

/-- capA, the cap at rest on the left end (units −4 .. −1). -/
def capA : List Pt := {lean_list(capA)}

/-- The rake gun, at unit 0 (units 0 .. 2). -/
def gun : List Pt := {lean_list(G)}

/-- The even translation into the box of `Gump.Bits` (moves units by {V[0] // 2}). -/
def frame : Pt := ⟨{V[0]}, {V[1]}, {V[2]}⟩

end Gump.Line''')

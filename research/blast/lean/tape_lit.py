#!/usr/bin/env python3
"""Writes Gump/ClockLitData.lean for the lit clock's transient (Gump/ClockLit.lean) and checks its formulas against
reference/oracle.py.

    python3 research/blast/lean/tape_lit.py > research/blast/lean/Gump/ClockLitData.lean

The lit clock of N units (capL, N units of wire C, capR moved N units, the cell (1,0,4) of unit N / 2) at generation
2m, for 2m <= 2 * ceil(N/2) - 2, is unit by unit: capL's units (-4 .. -1), on the units 0 .. N - 1 the hex letters
f (15, the rake) at N/2 + m, 7 (wire B) at N/2 - m + 2i for i < m, b (11, wire C) elsewhere, and capR's units.
Checked here for N = 6 .. 30 at every such m (this tests the word family's formula; Gump/ClockLit.lean proves it for
every N >= 6, `lit_word`, and that its last word, the rake at unit N - 1, is the surgery's state, `FL_entry`).
"""
import sys
from tape_lib import load, orbit_box, tr, unit, units, lean_list

ob = load('research/signals/objects/clock-C.json')
capL = [tuple(c) for c in ob['capL']]
capR = [tuple(c) for c in ob['capR']]
U = [tuple(c) for c in ob['unit']]
IGN = tuple(ob['ignite'])
ST = [(0, 1, 2), (0, 1, 4)]; SI = [(1, 0, 0), (1, 0, 2), (1, 0, 4), (0, 2, 3)]
hexc = lambda h: set(ST) | {SI[j] for j in range(4) if h >> j & 1}
capLU = {u: sorted(tr(c, -u) for c in capL if unit(c) == u) for u in range(-4, 0)}
capRU = {u: sorted(tr(c, -u) for c in capR if unit(c) == u) for u in range(0, 4)}
assert sorted(c for u in capLU for c in (tr(q, u) for q in capLU[u])) == sorted(capL)
assert sorted(c for u in capRU for c in (tr(q, u) for q in capRU[u])) == sorted(capR)


def lit(N):
    return frozenset(set(capL) | {tr(c, k) for c in U for k in range(N)} | {tr(c, N) for c in capR} | {tr(IGN, N // 2)})


def LW(N, m, u):
    h = N // 2
    if u == h + m: return 15
    if h - m <= u < h + m and (u - (h - m)) % 2 == 0: return 7
    return 11


def F(N, m):
    s = set(capL) | {tr(c, N) for c in capR}
    for u in range(N):
        s |= {tr(c, u) for c in hexc(LW(N, m, u))}
    return frozenset(s)


ok = True
for N in range(6, 31):
    mmax = (N + 1) // 2 - 1
    o = orbit_box(lit(N), 2 * mmax)
    good = all(o[2 * m] == F(N, m) for m in range(mmax + 1))
    ok &= good
    print(('PASS' if good else 'FAIL'), f'N = {N}: generation 2m is the word for m = 0 .. {mmax}', file=sys.stderr, flush=True)
# "At no earlier generation" (Gump/ClockLitFirst.lean): for even N the units <= 2 at generation N - 3 are the same for
# every N and differ from those of each of the 26 base states (the lit clock of 6 units at generations 41 .. 66); the
# first differing cell for each base time is `wit` there. For odd N the left end at N - 3 is that of 4 base times.
o6 = orbit_box(lit(6), 41 + 26)
assert o6[41 + 26] == o6[41]
base = [units(o6[41 + n], -99, 2) for n in range(26)]
left = {N: units(orbit_box(lit(N), N - 3)[N - 3], -99, 2) for N in range(6, 21, 2)}
good = all(left[N] == left[6] for N in left) and all(base[n] != left[6] for n in range(26))
ok &= good
wit = [sorted(base[n] ^ left[6])[0] for n in range(26)]
print(('PASS' if good else 'FAIL'), 'even N = 6 .. 20: the units <= 2 at generation N - 3 are on no base state; wit =',
      '[' + ', '.join(f'⟨{x}, {y}, {z}⟩' for x, y, z in wit) + ']', file=sys.stderr)
odd = {N: [n for n in range(26) if base[n] == units(orbit_box(lit(N), N - 3)[N - 3], -99, 2)] for N in (7, 9, 11)}
print('odd N: base times whose units <= 2 equal the lit clock\'s at N - 3:', odd, file=sys.stderr)
if not ok:
    sys.exit(1)
print(f'''/-
Generated by tape_lit.py (do not edit): the units of the clock's caps (research/signals/objects/clock-C.json), each
moved to unit 0: capL on the units -4 .. -1, capR on the units 0 .. 3.
-/
import Gump.TapeBase

namespace Gump.Clock
open Gump

/-- capL's cells on unit u (u = -4 .. -1), moved to unit 0. -/
def capLU : Int → List Pt''')
for u in range(-4, 0):
    print(f'  | {u} => {lean_list(capLU[u])}')
print('  | _ => []')
print('''
/-- capR's cells on unit u (u = 0 .. 3), moved to unit 0. -/
def capRU : Int → List Pt''')
for u in range(0, 4):
    print(f'  | {u} => {lean_list(capRU[u])}')
print('  | _ => []')
print('\nend Gump.Clock')

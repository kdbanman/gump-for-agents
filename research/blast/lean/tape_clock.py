#!/usr/bin/env python3
"""Writes Gump/ClockData.lean: the base cycle of the shuttle clock (research/signals/objects/clock-C.json, README
section 11, the surgery of research/signals/prove_clock.py) and the lit clocks for N = 1 .. 5, and checks with
reference/oracle.py every base fact that Gump/Clock.lean has the kernel check, and the surgery itself.

    python3 research/blast/lean/tape_clock.py > research/blast/lean/Gump/ClockData.lean

Base: the clock of N0 = 6 units lit by one cell; its cycle X(s), period p = 26, cut at unit m = 3, with
tR = 5, ta = 11, tb = 24, tb' = tb - p = -2 (times of the cycle counted from generation T0 = 22 of the lit run).
The Lean file stores X0 = X(t0) with t0 = tb' - 5 = -7. Checks, with tau the move by one unit:
  B0  X has period exactly p;
  B1  X(s) = tau X(s - 2) on units m, m + 1 for tb' - 3 <= s <= ta;
  B2  X(s) = tau X(s + 2) on units m, m + 1 for ta - 3 <= s <= tb;
  B3  X(ta + 1) = X(ta - 3) on units <= m + 1;   B4  X(tb + 1) = X(tb - 3) on units >= m - 1;
  B5  X(s) = X(tR) on units m - 1 .. m + 1 only for s = tR in a period;
  S   every X(s) lies in the units -4 .. N0 + 3.
Test the proof does not need: the surgery Y_j (README section 11; c_i as Gump.Clock.chart) for j = 1 .. 6 is
an oracle orbit of exact period 4(N0 + j) + 2 from T0 = tR, and the lit clock of N0 + j units falls into it.
Lit clocks N = 1 .. 5: from generation max(N - 2, 0) an oscillator of exact period 4N + 2 (oracle).
"""
import sys
from tape_lib import load, orbit, tr, unit, units, shift, lean_list

ob = load('research/signals/objects/clock-C.json')
capL = [tuple(c) for c in ob['capL']]
U = [tuple(c) for c in ob['unit']]
capR = [tuple(c) for c in ob['capR']]
IGN = tuple(ob['ignite'])
N0, m, tR, ta, tb = 6, 3, 5, 11, 24
p = 4 * N0 + 2
tb1 = tb - p
t0 = tb1 - 5
INF = 10 ** 6
ok = True


def report(name, good):
    global ok
    ok &= bool(good)
    print(('PASS ' if good else 'FAIL ') + name, file=sys.stderr, flush=True)


def lit(N):
    return frozenset(set(capL) | {tr(c, k) for c in U for k in range(N)} | {tr(c, N) for c in capR} | {tr(IGN, N // 2)})


T0 = 2 * N0 + 10
o = orbit(lit(N0), T0 + p + 1)
X = lambda s: o[T0 + (s % p)]
report('B0  the lit clock of 6 units: from generation 22 an oscillator of exact period 26',
       o[T0 + p] == o[T0] and all(o[T0 + s] != o[T0] for s in range(1, p)))
b1 = lambda s: shift(units(X(s - 2), m - 1, m), 1) == units(X(s), m, m + 1)
b2 = lambda s: shift(units(X(s + 2), m - 1, m), 1) == units(X(s), m, m + 1)
report('B1', all(b1(s) for s in range(tb1 - 3, ta + 1)))
report('B2', all(b2(s) for s in range(ta - 3, tb + 1)))
report('B3', units(X(ta + 1), -INF, m + 1) == units(X(ta - 3), -INF, m + 1))
report('B4', units(X(tb + 1), m - 1, INF) == units(X(tb - 3), m - 1, INF))
report('B5', [s for s in range(p) if units(X(s), m - 1, m + 1) == units(X(tR), m - 1, m + 1)] == [tR])
report('S   every state of the cycle in units -4 .. 9', all(units(X(s), -4, N0 + 3) == X(s) for s in range(p)))


def chart(i, j, t):
    """c_i(t) of Gump.Clock.chart: three periods of chart i around its start S_i = tb' + 2i."""
    P = p + 4 * j
    S = tb1 + 2 * i

    def first(t):
        if t <= ta + 2 * i:
            return t - 2 * i
        if t <= ta + 4 * j - 2 * i:
            return ta - 3 + (t - ta - 2 * i - 1) % 4
        if t <= tb + 4 * j - 2 * i:
            return t - 4 * j + 2 * i
        return tb - 3 + (t - tb - 4 * j + 2 * i - 1) % 4
    if t <= S:
        return first(t + P) - p
    if t <= S + P:
        return first(t)
    return first(t - P) + p


def Y(j, t):
    s = set(units(X(chart(0, j, t)), -INF, m))
    for i in range(1, j):
        s |= shift(units(X(chart(i, j, t)), m, m), i)
    s |= shift(units(X(chart(j, j, t)), m, INF), j)
    return frozenset(s)


for j in range(1, 7):
    N = N0 + j
    P = 4 * N + 2
    ys = [Y(j, tR + k) for k in range(P + 1)]
    oy = orbit(ys[0], P)
    good = oy == ys and all(ys[k] != ys[0] for k in range(1, P))
    ol = orbit(lit(N), 2 * N + 10 + P)
    hit = ys[0] in ol[2 * N + 10:]
    report(f'Y   j = {j}: the surgery from T0 = tR is the oracle orbit for one period, of exact period {P}; the lit clock of {N} units falls into it', good and hit)

for N in range(1, N0):
    mu = max(N - 2, 0)
    P = 4 * N + 2
    ol = orbit(lit(N), mu + P)
    report(f'L   lit clock N = {N}: from generation {mu} an oscillator of exact period {P}',
           ol[mu + P] == ol[mu] and all(ol[mu + k] != ol[mu] for k in range(1, P)))
if not ok:
    print('SOME CHECKS FAILED', file=sys.stderr)
    sys.exit(1)
print('ALL PASS', file=sys.stderr)
print(f'''/-
Generated by tape_clock.py (do not edit): the shuttle clock of research/signals/objects/clock-C.json. capL, capR and
the ignition cell as in the file; X0, the state of the cycle of the lit clock of 6 units at the cycle's time
t0 = {t0} (generation {T0 + (t0 % p)} of the lit run), {len(X(t0))} cells.
-/
import Gump.TapeBase

namespace Gump.Clock
open Gump

/-- The left cap (units −4 .. −1). -/
def capL : List Pt := {lean_list(capL)}

/-- The right cap, at unit 0 (units 0 .. 3). -/
def capR : List Pt := {lean_list(capR)}

/-- The cycle of the clock of six units at its time t0 = {t0}. -/
def X0 : List Pt := {lean_list(X(t0))}

end Gump.Clock''')

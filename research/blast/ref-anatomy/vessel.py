#!/usr/bin/env python3
"""Vessels for the referee of `anatomy`, written from docs/AUTOMATON.md and reference/oracle.py alone.

  slab(H, K, D): 8 {111} layers s = x+y+z in {1,3,...,15}, periodic in the plane with period lattice generated by
                 H*a1 + K*a2 and D*a2, a1 = (2,-2,0), a2 = (2,0,-2) (doubled coordinates; a1.a2 = 4 = |a|^2/2, so
                 |x a1 + y a2|^2 / 8 = x^2 + xy + y^2).  Faces: layers s = 1 and s = 15; beneath: s = 3 and s = 13.
  hull(R):       all cells with |x|+|y|+|z| <= R (R odd, about a cube centre).  Faces: d.p = R for the 8 d;
                 beneath: d.p = R - 2.

  python3 vessel.py t63|tube60|h63 [swap]    -> scratch/geom_NAME[_swap].txt (graph for fd.c) + returns dict

Every cell: 12 neighbour ids (N = the dead outside).  `swap` replaces one neighbour of one cell by a wrong cell
(negative control for the validation).
"""
import sys, os, itertools
import numpy as np

SCR = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'scratch', 'blast', 'ref-anatomy')


def offsets(axis):
    a = axis
    b, c = [i for i in range(3) if i != a]
    offs = []
    for sb in (2, -2):
        for sc in (2, -2):
            o = [0, 0, 0]; o[b] = sb; o[c] = sc; offs.append(tuple(o))
    for sa in (1, -1):
        for t in (b, c):
            for st in (1, -1):
                o = [0, 0, 0]; o[a] = sa; o[t] = st; offs.append(tuple(o))
    return offs


def axis_of(p):
    odd = [i for i in range(3) if p[i] % 2]
    assert len(odd) == 1
    return odd[0]


def slab(H, K, D, nl=8):
    v1 = (2 * H + 2 * K, -2 * H, -2 * K)
    v2 = (2 * D, 0, -2 * D)

    def canon(p):
        x, y, z = p
        # reduce y into [0, 2H) with v1 (y changes by -2H per v1), then z into [0, 2D) with v2
        m = (y - (y % (2 * H))) // (2 * H)          # y - 2H*m' ... adding m*v1 changes y by -2H*m
        x, y, z = x + m * v1[0], y + m * v1[1], z + m * v1[2]
        n = (z - (z % (2 * D))) // (2 * D)
        x, y, z = x + n * v2[0], y + n * v2[1], z + n * v2[2]
        assert 0 <= y < 2 * H and 0 <= z < 2 * D
        return (x, y, z)

    cells = []
    for s in range(1, 2 * nl, 2):
        for y in range(2 * H):
            for z in range(2 * D):
                x = s - y - z
                p = (x, y, z)
                if sum(c % 2 for c in p) == 1:
                    cells.append(p)
    idx = {p: i for i, p in enumerate(cells)}
    N = len(cells)
    assert N == 3 * H * D * nl, (N, H, D)
    nb = np.full((N, 12), N, int)
    for i, p in enumerate(cells):
        for j, o in enumerate(offsets(axis_of(p))):
            q = (p[0] + o[0], p[1] + o[1], p[2] + o[2])
            s = sum(q)
            if 1 <= s <= 2 * nl - 1:
                nb[i, j] = idx[canon(q)]
    lay = np.array([sum(p) for p in cells])
    faces = [np.where(lay == 1)[0], np.where(lay == 2 * nl - 1)[0]]
    beneath = [np.where(lay == 3)[0], np.where(lay == 2 * nl - 3)[0]]
    third = [np.where(lay == 5)[0], np.where(lay == 2 * nl - 5)[0]]
    # in-plane position (unwrapped modulo the lattice) of each cell: components along a1, a2 in units of |a|
    return dict(name=f'slab({H},{K}),(0,{D})', cells=cells, nb=nb, faces=faces, beneath=beneath, third=third, canon=canon,
                idx=idx, N=N, lay=lay, v1=v1, v2=v2, per=2 * H * D, kind='slab', HKD=(H, K, D))


def hull(R):
    cells = []
    for x in range(-R, R + 1):
        for y in range(-R, R + 1):
            for z in range(-R, R + 1):
                if abs(x) + abs(y) + abs(z) <= R and (x % 2) + (y % 2) + (z % 2) == 1:
                    cells.append((x, y, z))
    idx = {p: i for i, p in enumerate(cells)}
    N = len(cells)
    nb = np.full((N, 12), N, int)
    for i, p in enumerate(cells):
        for j, o in enumerate(offsets(axis_of(p))):
            q = (p[0] + o[0], p[1] + o[1], p[2] + o[2])
            if q in idx:
                nb[i, j] = idx[q]
    faces, beneath, third = [], [], []
    for d in itertools.product((1, -1), repeat=3):
        s = np.array([d[0] * p[0] + d[1] * p[1] + d[2] * p[2] for p in cells])
        faces.append(np.where(s == R)[0]); beneath.append(np.where(s == R - 2)[0]); third.append(np.where(s == R - 4)[0])
    return dict(name=f'hull({R})', cells=cells, nb=nb, faces=faces, beneath=beneath, third=third, idx=idx, N=N, kind='hull', R=R)


VESSELS = {'t63': lambda: slab(1, 4, 21), 'tube60': lambda: slab(1, 8, 20), 'h63': lambda: hull(11),
           't48': lambda: slab(4, 0, 4), 'h45': lambda: hull(9), 't84': lambda: slab(1, 4, 28),
           'tube84': lambda: slab(1, 12, 28), 't108': lambda: slab(6, 0, 6)}


def get(name):
    return VESSELS[name]()


def write(name, swap=False):
    v = get(name)
    nb = v['nb'].copy()
    if swap:
        i0 = v['N'] // 2
        bad = next(j for j in range(v['N']) if j != i0 and j not in set(nb[i0]))
        nb[i0, 0] = bad
    os.makedirs(SCR, exist_ok=True)
    fn = os.path.join(SCR, f'geom_{name}{"_swap" if swap else ""}.txt')
    with open(fn, 'w') as f:
        f.write(f'{v["N"]} {len(v["faces"])}\n')
        for i in range(v['N']):
            f.write(' '.join(map(str, nb[i])) + '\n')
        for fc in v['faces']:
            f.write(f'{len(fc)} ' + ' '.join(map(str, fc)) + '\n')
        for key in ('beneath', 'third'):                 # read by fd2.c only; fd.c stops after the faces
            for fc in v[key]:
                f.write(f'{len(fc)} ' + ' '.join(map(str, fc)) + '\n')
    return fn, v


if __name__ == '__main__':
    name = sys.argv[1]
    fn, v = write(name, swap=len(sys.argv) > 2)
    print(fn, v['name'], 'cells', v['N'], 'faces', len(v['faces']), 'face cells', [len(f) for f in v['faces']],
          'beneath', [len(b) for b in v['beneath']])
    # symmetry of the graph: every neighbour relation is mutual
    nb = v['nb']; N = v['N']
    assert all((nb[j] == i).sum() == (nb[i] == j).sum() for i in range(N) for j in nb[i] if j < N)
    if v['kind'] == 'slab':
        H, K, D = v['HKD']
        vs = sorted((x * x + x * y + y * y, x, y) for m in range(-12, 13) for j in range(-12, 13)
                    for x, y in [(m * H, m * K + j * D)] if (x, y) != (0, 0))
        print('shortest loops^2:', [q for q, _, _ in vs[:8:2]])

#!/usr/bin/env python3
"""ref-chain: generate RefChainCellLaw.lean, which checks ChainCoins.lean's one-cell law (death3, death2,
aliveProbR) against the death probabilities computed here from reference/oracle.py's BIRTH/SURVIVE and exact
rational coins rho1 = 11/25, rho2 = 21/50 (and a second pair 1/3, 3/7).

  python3 research/blast/ref-chain/gen_cell_law.py > research/blast/ref-chain/RefChainCellLaw.lean
"""
import os, sys
from fractions import Fraction as Fr
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', 'reference'))
from oracle import BIRTH, SURVIVE

def law(m1, m2, r1, r2):
    from math import comb
    p = {}
    for j in range(m1 + 1):
        for l in range(m2 + 1):
            p[j + l] = p.get(j + l, 0) + comb(m1, j) * r1**j * (1 - r1)**(m1 - j) * comb(m2, l) * r2**l * (1 - r2)**(m2 - l)
    return p

def death(m1, m2, r1, r2, s, k):
    return sum(q for b, q in law(m1, m2, r1, r2).items() if not ((k + b) in (SURVIVE if s else BIRTH)))

lean = lambda f: f"({f.numerator}/{f.denominator} : ℝ)"
print("/- generated by gen_cell_law.py: ChainCoins' one-cell law against the oracle's rule, exact rationals. -/")
print("import GumpMath.ChainBits\nopen Gump.Chain Gump.Chain.Bits\n")
n = 0
for (r1, r2) in ((Fr(11, 25), Fr(21, 50)), (Fr(1, 3), Fr(3, 7))):
    for s in (False, True):
        for k in range(7):
            v = death(2, 1, r1, r2, s, k)
            print(f"example : death3 {lean(r1)} {lean(r2)} {str(s).lower()} {k} = {lean(v)} := by\n"
                  f"  norm_num [death3, Finset.sum_range_succ, aliveNext, coin3]")
            print(f"example : 1 - aliveProbR {lean(r1)} {lean(r2)} 2 1 {k} {str(s).lower()} = {lean(v)} := by\n"
                  f"  norm_num [aliveProbR, binR, Finset.sum_range_succ, Gump.rule, Nat.choose]")
            n += 2
        for k in range(3):
            v = death(2, 0, r1, r2, s, k)
            print(f"example : death2 {lean(r1)} {str(s).lower()} {k} = {lean(v)} := by\n"
                  f"  norm_num [death2, Finset.sum_range_succ, aliveNext, coin2]")
            n += 1
print(f"-- {n} examples")

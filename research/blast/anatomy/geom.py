#!/usr/bin/env python3
"""Vessels for an.c, built from docs/AUTOMATON.md (doubled coordinates) only.

    python3 geom.py slab H K D [NL] # NL (default 8) {111} layers s = x+y+z = 1..2NL-1, periodic in the plane by (H,K),(0,D)
    python3 geom.py hull R          # all cells with |x|+|y|+|z| <= R (R odd)

Hexagonal basis: e1 = (2,-2,0), e2 = (2,0,-2) (60 degrees, |a e1 + b e2|^2 = 8 (a^2 + ab + b^2)); the period
lattice is generated by H e1 + K e2 and D e2. Writes NAME.bin (graph for an.c) and NAME.json (coordinates) under
research/scratch/blast/anatomy/. 2D positions are in units of |e1| (the hexagonal lattice constant; the kagome
nearest-neighbour distance is 1/2), on the plane normal to the face's diagonal.
"""
import json, math, os, struct, sys
from math import gcd

HERE = os.path.dirname(os.path.abspath(__file__))
SCR = os.path.abspath(os.path.join(HERE, '..', '..', 'scratch', 'blast', 'anatomy'))
NL = 8


def nbrs(p):
    a = [i for i in range(3) if p[i] % 2]
    assert len(a) == 1
    a = a[0]
    b, c = [i for i in range(3) if i != a]
    out = []
    for sb in (2, -2):
        for sc in (2, -2):
            q = list(p); q[b] += sb; q[c] += sc; out.append(tuple(q))
    for sa in (1, -1):
        for o in (b, c):
            for so in (1, -1):
                q = list(p); q[a] += sa; q[o] += so; out.append(tuple(q))
    return out


def pos2d(p, d=(1, 1, 1)):
    x, y, z = (p[i] * d[i] for i in range(3))
    return [(x - y) / math.sqrt(2) / (2 * math.sqrt(2)), (x + y - 2 * z) / math.sqrt(6) / (2 * math.sqrt(2))]


def slab(H, K, D, nl=NL):
    def canon(p):
        s = p[0] + p[1] + p[2]
        if s < 1 or s > 2 * nl - 1:
            return None
        y0, z0 = p[1] % 2, p[2] % 2
        a, b = (y0 - p[1]) // 2, (z0 - p[2]) // 2
        m = a // H
        a -= m * H; b -= m * K; b %= D
        y, z = y0 - 2 * a, z0 - 2 * b
        return (s - y - z, y, z)
    cells = []
    for s in range(1, 2 * nl, 2):
        for a in range(H):
            for b in range(D):
                for y0, z0 in ((0, 0), (1, 0), (0, 1)):
                    y, z = y0 - 2 * a, z0 - 2 * b
                    p = (s - y - z, y, z)
                    assert canon(p) == p
                    cells.append(p)
    idx = {p: i for i, p in enumerate(cells)}
    nb = []
    for p in cells:
        row = []
        for q in nbrs(p):
            c = canon(q)
            row.append(-1 if c is None else idx[c])
        nb.append(row)
    lay = lambda s: [i for i, p in enumerate(cells) if sum(p) == s]
    faces = [(lay(1), lay(3)), (lay(2 * nl - 1), lay(2 * nl - 3))]
    v1 = (2 * H + 2 * K, -2 * H, -2 * K); v2 = (2 * D, 0, -2 * D)
    groups = []
    for dv in ((-1, 1, 1), (1, -1, 1), (1, 1, -1)):
        P = gcd(abs(sum(a * b for a, b in zip(dv, v1))), abs(sum(a * b for a, b in zip(dv, v2))))
        layers = [[i for i, p in enumerate(cells) if sum(a * b for a, b in zip(dv, p)) % P == t] for t in range(1, P, 2)]
        assert sum(map(len, layers)) == len(cells)
        groups.append(layers)
    meta = dict(kind='slab', H=H, K=K, D=D, cells=cells, period=[pos2d(v1), pos2d(v2)],
                facepos=[[pos2d(cells[i]) for i in f[0]] for f in faces],
                underpos=[[pos2d(cells[i]) for i in f[1]] for f in faces])
    return f'slab_{H}_{K}_{D}' + ('' if nl == NL else f'_L{nl}'), cells, nb, faces, groups, meta


def hull(R):
    assert R % 2 == 1
    cells = [(x, y, z) for x in range(-R, R + 1) for y in range(-R, R + 1) for z in range(-R, R + 1)
             if (x % 2) + (y % 2) + (z % 2) == 1 and abs(x) + abs(y) + abs(z) <= R]
    idx = {p: i for i, p in enumerate(cells)}
    nb = [[idx.get(q, -1) for q in nbrs(p)] for p in cells]
    faces, fpos, upos, mapped = [], [], [], []
    for d in [(a, b, c) for a in (1, -1) for b in (1, -1) for c in (1, -1)]:
        dot = lambda p: p[0] * d[0] + p[1] * d[1] + p[2] * d[2]
        fc = [i for i, p in enumerate(cells) if dot(p) == R]
        uc = [i for i, p in enumerate(cells) if dot(p) == R - 2]
        faces.append((fc, uc))
        fpos.append([pos2d(cells[i], d) for i in fc]); upos.append([pos2d(cells[i], d) for i in uc])
        mapped.append([[cells[i][k] * d[k] for k in range(3)] for i in fc])
    meta = dict(kind='hull', R=R, cells=cells, facepos=fpos, underpos=upos, mapped=mapped)
    return f'hull_{R}', cells, nb, faces, [], meta


def write(name, cells, nb, faces, groups, meta):
    os.makedirs(SCR, exist_ok=True)
    out = [len(cells)]
    for r in nb:
        out += r
    out.append(len(faces))
    for fc, uc in faces:
        out += [len(fc)] + fc + [len(uc)] + uc
    out.append(len(groups))
    for g in groups:
        out.append(len(g))
        for l in g:
            out += [len(l)] + l
    path = os.path.join(SCR, name + '.bin')
    open(path, 'wb').write(struct.pack(f'<{len(out)}i', *out))
    meta['faces'] = [f[0] for f in faces]; meta['under'] = [f[1] for f in faces]
    json.dump(meta, open(os.path.join(SCR, name + '.json'), 'w'))
    return path


def build(kind, *args):
    v = slab(*args) if kind == 'slab' else hull(*args)
    return write(*v), v


if __name__ == '__main__':
    path, v = build(sys.argv[1], *map(int, sys.argv[2:]))
    print(path, 'cells', len(v[1]), 'face cells', len(v[3][0][0]), 'under', len(v[3][0][1]), 'groups', [len(g) for g in v[4]])

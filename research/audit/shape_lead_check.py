import csv, math, os
from math import gcd
HERE = os.path.dirname(os.path.abspath(__file__))

def hnf(v, w):                      # canonical generators (a, k), (0, b), 0 <= k < b, of the lattice Z v + Z w
    (p, q), (r, s) = v, w
    while r:
        t = p // r; p, q, r, s = r, s, p - t * r, q - t * s
    if p < 0: p, q = -p, -q
    s = abs(s)
    return (p, q % s, s)

ROT = lambda v: (-v[1], v[0] + v[1])       # 60 degrees: u1 -> u2, u2 -> u2 - u1
REF = lambda v: (v[1], v[0])               # u1 <-> u2
def cls(a, k, b):
    out = set(); v, w = (a, k), (0, b)
    for _ in range(6):
        v, w = ROT(v), ROT(w); out.add(hnf(v, w)); out.add(hnf(REF(v), REF(w)))
    return min(out)
def systole2(a, k, b, R=30):
    return min(X * X + X * Y + Y * Y for x in range(-R, R + 1) for y in range(-R, R + 1) if (x, y) != (0, 0)
               for X, Y in [(a * x, k * x + b * y)])

for name in ("A72", "A60"):
    rows = list(csv.DictReader(open(os.path.join(HERE, "..", "shape", "data", name + ".csv"))))
    groups, shapes = {}, {}
    print(name)
    for r in rows:
        a, k, b = int(r["a"]), int(r["k"]), int(r["b"])
        s2 = systole2(a, k, b); c = cls(a, k, b)
        lt = math.log(2 * float(r["exposure"]) / int(r["face_deaths"])); e = 1 / math.sqrt(int(r["face_deaths"]))
        ok = (s2 == int(r["systole2"])) and abs(lt - float(r["ln_tau_face"])) < 6e-4 and a * b * 3 == int(name[1:])
        print(f"  {r['torus']:>10}  ({a},{k}),(0,{b})  class {c}  systole2 {s2}  ln tau {lt:.4f} +- {e:.4f}  "
              f"fw share {float(r['fw_share']):.3f}  {'ok' if ok else 'MISMATCH with the csv'}")
        groups.setdefault(s2, []).append((lt, e)); shapes.setdefault((s2, c), []).append((lt, e))
    chi = dof = 0
    for s2 in sorted(groups):
        g = groups[s2]; w = [1 / e ** 2 for _, e in g]; m = sum(wi * y for wi, (y, _) in zip(w, g)) / sum(w)
        chi += sum(wi * (y - m) ** 2 for wi, (y, _) in zip(w, g)); dof += len(g) - 1
        ns = len({c for (s, c) in shapes if s == s2})
        print(f"  systole2 {s2:>2}: {len(g)} presentations, {ns} shape(s), mean {m:.4f} +- {1 / math.sqrt(sum(w)):.4f}")
    print(f"  agreement within systole groups: chi2 {chi:.1f} on {dof}")
    for (s2, c), g in sorted(shapes.items()):
        if len({cc for (s, cc) in shapes if s == s2}) > 1:
            w = [1 / e ** 2 for _, e in g]; m = sum(wi * y for wi, (y, _) in zip(w, g)) / sum(w)
            print(f"    systole2 {s2}, shape {c}: {m:.4f} +- {1 / math.sqrt(sum(w)):.4f} ({len(g)} presentation(s))")

#!/usr/bin/env python3
"""The lead's fit of an additive "wrapping law" to every wide wrapped face on file (2026-11-15).

Claim under test: a wrapped (periodic) face layer of A cells lives

    ln tau_face = a + c (A - 63) - (A - A0) * sum over closed-loop directions v of the face of k(|v|^2)

with k(q) > 0 for the short loops q = 12, 13, 16, 19 and k(q) = 0 for q >= 21: each short way round
the face lowers the price per cell by a fixed amount, and all the lines meet at A0.

Data (nothing is run here):
  - the nine equilateral tori measured on the owner's card, recomputed from the rows
    (research/data/gpu_local_eqtorus/eqtorus_*.csv; ln(2 exposure / face deaths));
  - every other periodic class with shortest loop^2 >= 12 in research/constant/out/points.txt
    (census classes at A = 48, 60, 72 and the firewall-resolved slabs; `python3 research/constant/load.py --check`
    regenerates that file).
Loop directions are counted one per +-v, from the reduced Gram triple (g11, 2 g12, g22) of the period lattice.

Usage:  python3 research/audit/wrap_law_lead.py            # fit and tables
        python3 research/audit/wrap_law_lead.py --noslab   # without the fwslab points (A >= 84 slabs)
        python3 research/audit/wrap_law_lead.py --predict H K D [H K D ...]
              # forecast for the torus with period lattice (H, K), (0, D), from the parameters FROZEN below

FROZEN (the fit of 2026-11-15 13:00 UTC to the 32 faces, committed before any new face was measured):
    a = 13.1629, c = 0.20860, A0 = 21.25, k(12) = 0.002918, k(13) = 0.002271, k(16) = 0.001353, k(19) = 0.000338
"""
import csv, glob, math, re, sys
import numpy as np

QS = [12, 13, 16, 19]            # loop^2 values given a discount; 21 and above get none
NOSLAB = '--noslab' in sys.argv


def shorts(g, cap=20):
    a, b, c = g
    out = []
    for m in range(0, 14):
        for n in range(-14, 15):
            if m == 0 and n <= 0:
                continue
            q = a * m * m + b * m * n + c * n * n
            if q <= cap:
                out.append(q)
    return sorted(out)


def gram_of_hnf(h, k, d):
    """Period lattice generated by (h, k) and (0, d) in the hexagonal basis |xe1 + ye2|^2 = x^2 + xy + y^2."""
    # brute force: all loop^2 up to 40 are what we need, so just return a function of vectors
    vs = []
    for m in range(-12, 13):
        for n in range(-12, 13):
            if (m, n) <= (0, 0):
                continue
            x, y = m * h, m * k + n * d
            vs.append(x * x + x * y + y * y)
    return sorted(q for q in vs if q <= 20)


FROZEN = dict(a=13.1629, c=0.20860, A0=21.25, k={12: 0.002918, 13: 0.002271, 16: 0.001353, 19: 0.000338})


def predict(h, k, d):
    A_ = 3 * h * d
    loops = gram_of_hnf(h, k, d)
    disc = sum(FROZEN['k'].get(q, 0.0) if q >= 12 else float('nan') for q in loops)
    return A_, loops, FROZEN['a'] + FROZEN['c'] * (A_ - 63) - (A_ - FROZEN['A0']) * disc


if '--predict' in sys.argv:
    v = [int(x) for x in sys.argv[sys.argv.index('--predict') + 1:]]
    for i in range(0, len(v), 3):
        A_, loops, lt = predict(*v[i:i + 3])
        print(f'({v[i]},{v[i+1]}),(0,{v[i+2]})  A = {A_}  loops^2 <= 20: {loops}  forecast ln tau_face = {lt:.4f}'
              + ('' if not loops or loops[0] >= 12 else '   (a loop shorter than 12: outside the law)'))
    sys.exit(0)

pts = []   # (A, label, lnτ, se, short loops ≤ 20, source)

# the card's nine equilateral tori
for f in sorted(glob.glob('research/data/gpu_local_eqtorus/eqtorus_*.csv')):
    E = F = 0
    for r in csv.DictReader(open(f)):
        E += int(r['exposure']); F += int(r['face']); A = int(r['A']); tor = r['torus']
    h, k, d = (int(x) for x in tor.split(','))
    pts.append((A, 'eq(%s)' % tor, math.log(2 * E / F), 1 / math.sqrt(F), gram_of_hnf(h, k, d), 'card'))
card_A = {p[0] for p in pts}

sec = None
for l in open('research/constant/out/points.txt'):
    if l.startswith('PERIODIC'):
        sec = 'P'; continue
    if not l.strip():
        continue
    if l[0].isalpha():
        sec = None; continue
    if sec != 'P':
        continue
    m = re.match(r'\s*(\d+)\s+\((\d+), (-?\d+), (\d+)\)\s+\((\d+), (-?\d+), (\d+)\)\s+(\S+x\S+)?\s*([\d.]+)\s+([\d.]+)\s+(\d+)\s+([\d.]+)', l)
    if not m:
        continue
    A = int(m.group(1)); g = tuple(int(m.group(i)) for i in (2, 3, 4))
    allq = shorts(g, cap=10 ** 6)
    if allq[0] < 12:
        continue
    if g[0] == g[1] == g[2]:           # equilateral: the card's value is used instead
        continue
    rect = m.group(8) or ''
    fw = float(m.group(12))
    src = 'slab' if (rect and A >= 84) else 'census'
    if NOSLAB and src == 'slab':
        continue
    pts.append((A, (rect or str(g)), float(m.group(9)), float(m.group(10)), shorts(g), src))

pts.sort()
y = np.array([p[2] for p in pts]); se = np.array([p[3] for p in pts]); A = np.array([p[0] for p in pts], float)
N = np.array([[p[4].count(q) for q in QS] for p in pts], float)


def fit(A0):
    X = np.column_stack([np.ones(len(pts)), A - 63] + [-(A - A0) * N[:, j] for j in range(len(QS))])
    W = 1 / se
    beta, *_ = np.linalg.lstsq(X * W[:, None], y * W, rcond=None)
    r = (y - X @ beta) / se
    cov = np.linalg.inv((X * W[:, None]).T @ (X * W[:, None]))
    return float(r @ r), beta, np.sqrt(np.diag(cov)), r


best = min((fit(a0)[0], a0) for a0 in np.arange(0, 45.01, 0.25))
chi2, A0 = best
_, beta, err, r = fit(A0)
lo = [a0 for a0 in np.arange(0, 45.01, 0.25) if fit(a0)[0] <= chi2 + 1]
dof = len(pts) - 3 - len(QS)
print(f'{len(pts)} faces; chi2 = {chi2:.1f} on {dof}; A0 = {A0:.2f} (chi2 + 1: {min(lo):.2f} to {max(lo):.2f})')
print(f'a = {beta[0]:.4f} ± {err[0]:.4f}   c = {beta[1]:.5f} ± {err[1]:.5f}')
for j, q in enumerate(QS):
    print(f'k({q}) = {beta[2 + j]:.5f} ± {err[2 + j]:.5f} per cell per loop direction')
print()
print('   A  face             lnτ       se     short loops        fit      resid/se  source')
for p, ri, fi in zip(pts, r, y - r * se):
    print(f'{p[0]:4d}  {p[1]:15s} {p[2]:8.4f} {p[3]:.4f}  {str(p[4]):18s} {fi:8.4f}  {ri:+6.1f}    {p[5]}')

# the same data with no discount at all, and with the discount as a constant offset per direction (not per cell)
X0 = np.column_stack([np.ones(len(pts)), A - 63]); W = 1 / se
b0, *_ = np.linalg.lstsq(X0 * W[:, None], y * W, rcond=None)
print(f'\nno wrapping term: chi2 = {float((((y - X0 @ b0) / se) ** 2).sum()):.0f} on {len(pts) - 2}')
X1 = np.column_stack([np.ones(len(pts)), A - 63] + [-N[:, j] for j in range(len(QS))])
b1, *_ = np.linalg.lstsq(X1 * W[:, None], y * W, rcond=None)
print(f'constant offset per direction (no growth with A): chi2 = {float((((y - X1 @ b1) / se) ** 2).sum()):.0f} on {len(pts) - 2 - len(QS)}')
# only the faces with every loop^2 >= 21: do they share the equilateral line?
long_ = [i for i, p in enumerate(pts) if not p[4]]
bl, *_ = np.linalg.lstsq(X0[long_] * W[long_, None], y[long_] * W[long_], rcond=None)
rl = (y[long_] - X0[long_] @ bl) / se[long_]
print(f'faces with every loop^2 >= 21: {len(long_)}; one line: a = {bl[0]:.4f}, c = {bl[1]:.5f}, chi2 = {float(rl @ rl):.1f} on {len(long_) - 2}')

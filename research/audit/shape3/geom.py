#!/usr/bin/env python3
"""Geometry of an 8-layer {111} slab with twisted in-plane periods, written for the review of research/shape3 from
docs/AUTOMATON.md alone (doubled-coordinate offsets of section 2; nothing imported from research/shape*, from
research/audit/shape/ or from ts.c / ts3.c).

Torus label (a, k, b): in-plane period lattice generated by the cube vectors (a, k) and (0, b) in the basis
u1 = (1, 0, -1), u2 = (0, 1, -1); index n = a b, face area A = 3 n.  A cell is a doubled point p with exactly one odd
coordinate and s = p.(1,1,1) in {1, 3, ..., 2M-1}; p ~ p + 2 (x, y, -x-y) for (x, y) in the lattice.

    python3 research/audit/shape3/geom.py 1 4 12      # summary: cells, layer counts per diagonal, multigraph check
"""
import math, os, struct, sys

M = 8
TDIAGS = [(-1, 1, 1), (1, -1, 1), (1, 1, -1)]   # the three body diagonals transverse to the slab normal (1,1,1)


def offsets(ax):
    """The 12 doubled offsets of a face with normal axis ax (AUTOMATON.md section 2)."""
    b, c = [t for t in range(3) if t != ax]
    out = []
    for sb in (2, -2):
        for sc in (2, -2):
            v = [0, 0, 0]; v[b] = sb; v[c] = sc; out.append(tuple(v))
    for o in (b, c):
        for sa in (1, -1):
            for so in (1, -1):
                v = [0, 0, 0]; v[ax] = sa; v[o] = so; out.append(tuple(v))
    return out


def canon(p, L):
    """Representative of p modulo 2 (x, y, -x-y), (x, y) in the lattice: X in [0, 2a), Y in [0, 2b)."""
    a, k, b = L
    X, Y, Z = p
    s = X + Y + Z
    q = X // (2 * a)            # translate by -q (a, k)
    X -= 2 * a * q; Y -= 2 * k * q
    Y %= 2 * b
    return (X, Y, s - X - Y)


def build(L, m=M):
    a, k, b = L
    cells = []
    for X in range(2 * a):
        for Y in range(2 * b):
            for t in range(m):
                s = 2 * t + 1
                Z = s - X - Y
                if (X % 2) + (Y % 2) + (Z % 2) == 1:
                    cells.append((X, Y, Z))
    idx = {c: i for i, c in enumerate(cells)}
    assert len(cells) == 3 * a * b * m, len(cells)
    nb = []
    for p in cells:
        ax = [t for t in range(3) if p[t] % 2][0]
        row = []
        for o in offsets(ax):
            q = (p[0] + o[0], p[1] + o[1], p[2] + o[2])
            s = sum(q)
            if s < 1 or s > 2 * m - 1:
                row.append(-1)
            else:
                row.append(idx[canon(q, L)])
        nb.append(row)
    # transverse layer index: s_d = d.p mod P_d, P_d = gcd of d.(2 g) over generators g of the lattice
    gens = [(a, k), (0, b)]
    diag_layers = []
    for d in TDIAGS:
        P = 0
        for x, y in gens:
            P = math.gcd(P, 2 * (d[0] * x + d[1] * y - d[2] * (x + y)))
        P = abs(P)
        lay = []
        for p in cells:
            sd = (d[0] * p[0] + d[1] * p[1] + d[2] * p[2]) % P
            assert sd % 2 == 1
            lay.append((sd - 1) // 2)
        diag_layers.append((P // 2, lay))
    face0 = [i for i, p in enumerate(cells) if sum(p) == 1]
    face1 = [i for i, p in enumerate(cells) if sum(p) == 2 * m - 1]
    return cells, nb, face0, face1, diag_layers


def write(L, path):
    cells, nb, f0, f1, dl = build(L)
    n = len(cells)
    with open(path + '.tmp', 'wb') as f:
        w = lambda *xs: f.write(struct.pack('<%di' % len(xs), *xs))
        w(n)
        for row in nb:
            w(*[n if x < 0 else x for x in row])
        w(len(f0), *f0); w(len(f1), *f1)
        w(len(dl))
        for nl, lay in dl:
            w(nl, *lay)
    os.replace(path + '.tmp', path)
    return cells


def check_T1(L):
    """Every in-slab neighbour pair satisfies T1 for every transverse diagonal: layer step in {0, +-1, +-2} (mod L_d),
    and the histogram over the 12 slots of a cell far from the faces is -2:1, -1:2, 0:6, 1:2, 2:1."""
    cells, nb, f0, f1, dl = build(L)
    bad = 0
    for nl, lay in dl:
        for i, row in enumerate(nb):
            for j in row:
                if j < 0:
                    continue
                dlt = (lay[j] - lay[i]) % nl
                if nl > 4 and dlt not in (0, 1, 2, nl - 1, nl - 2):
                    bad += 1
    return bad


if __name__ == '__main__':
    L = tuple(map(int, sys.argv[1:4]))
    cells, nb, f0, f1, dl = build(L)
    multi = sum(1 for row in nb if len([x for x in row if x >= 0]) != len(set(x for x in row if x >= 0)))
    print(f'{L}: {len(cells)} cells, faces {len(f0)} + {len(f1)}, transverse layers per diagonal {[x[0] for x in dl]}, '
          f'cells with a repeated neighbour {multi}, T1 violations {check_T1(L)}')

#!/usr/bin/env python3
"""Period lattices of a periodic {111} slab face, written independently of research/shape*/lattice*.py.

A face torus is the plane of cube columns modulo the lattice generated by (a, k), (0, b) in the cube coordinates
(i, j); index n = a*b, face area A = 3n cells.  A lattice vector (x, y) is the complex number x + y*w,
w = exp(i*pi/3), so |v|^2 = Q(x, y) = x^2 + xy + y^2 in units of one cube step |u1|^2 (the unit in which a
rectangular slab's side is counted).  Torus area in these units: n*sqrt(3)/2.

    python3 research/constant/lat.py 4 0 6        # invariants of one torus
    python3 research/constant/lat.py selftest     # checks against research/shape2/data/classes_A*.csv
"""
import cmath, math, sys

W = cmath.exp(1j * math.pi / 3)


def Q(x, y):
    return x * x + x * y + y * y


def reduce_basis(a, k, b):
    """Gauss reduction. Returns integer vectors u, v with Q(u) <= Q(v) and |2 B(u, v)| <= Q(u)."""
    u, v = (a, k), (0, b)
    while True:
        if Q(*u) > Q(*v):
            u, v = v, u
        bil = u[0] * v[0] + (u[0] * v[1] + u[1] * v[0]) / 2 + u[1] * v[1]
        m = round(bil / Q(*u))
        if m == 0:
            return u, v
        v = (v[0] - m * u[0], v[1] - m * u[1])


def gram(a, k, b):
    """(Q1, |2B|, Q2): isometry invariant of the lattice (the slab's in-plane point group contains reflections)."""
    u, v = reduce_basis(a, k, b)
    bil2 = 2 * u[0] * v[0] + u[0] * v[1] + u[1] * v[0] + 2 * u[1] * v[1]
    return (Q(*u), abs(bil2), Q(*v))


def modulus(a, k, b):
    """Shape modulus tau = v/u in the fundamental domain, folded to 0 <= Re tau <= 1/2 (reflection allowed)."""
    u, v = reduce_basis(a, k, b)
    zu, zv = u[0] + u[1] * W, v[0] + v[1] * W
    t = zv / zu
    if t.imag < 0:
        t = t.conjugate()
    return complex(abs(t.real), t.imag)


def eta_abs(t, terms=200):
    """|Dedekind eta(tau)|."""
    q = cmath.exp(2j * math.pi * t)
    p = cmath.exp(2j * math.pi * t / 24)
    for n in range(1, terms):
        p *= (1 - q ** n)
        if abs(q) ** n < 1e-18:
            break
    return abs(p)


def F_boson(a, k, b):
    """ln of the free (non-compact) boson partition function on the face torus, up to an additive constant:
    F = -1/2 ln(Im tau) - 2 ln|eta(tau)|.  Modular invariant; depends on the shape only, not on the size."""
    t = modulus(a, k, b)
    return -0.5 * math.log(t.imag) - 2 * math.log(eta_abs(t))


def vectors(a, k, b, qmax):
    """Q of every nonzero lattice vector with Q <= qmax (both signs counted)."""
    out = []
    R = int(math.sqrt(qmax) * 1.2 / 1) + 2
    # p*(a,k) + q*(0,b): |x| = |p| a <= sqrt(4 qmax / 3)
    pm = int(math.sqrt(4 * qmax / 3) / a) + 1
    for p in range(-pm, pm + 1):
        x = p * a
        # y range: Q = x^2 + x y + y^2 <= qmax  ->  |y + x/2| <= sqrt(qmax - 3 x^2 / 4)
        d = qmax - 0.75 * x * x
        if d < 0:
            continue
        ylo, yhi = -x / 2 - math.sqrt(d), -x / 2 + math.sqrt(d)
        qlo = math.ceil((ylo - p * k) / b); qhi = math.floor((yhi - p * k) / b)
        for q in range(qlo, qhi + 1):
            y = p * k + q * b
            if x == 0 and y == 0:
                continue
            qq = Q(x, y)
            if qq <= qmax:
                out.append(qq)
    return sorted(out)


def loop_sum(a, k, b, xi, kind='exp', rmax=40.0):
    """Sum over nonzero period vectors v of f(|v|/xi); f = exp(-r) or the modified Bessel function K0(r)."""
    qmax = (rmax * xi) ** 2 if xi * rmax > 3 else 9.0 * 4
    qmax = max(qmax, 4.0 * Q(*reduce_basis(a, k, b)[1]))
    qs = vectors(a, k, b, qmax)
    if kind == 'exp':
        return sum(math.exp(-math.sqrt(q) / xi) for q in qs)
    if kind == 'k0':
        from scipy.special import k0
        return float(sum(k0(math.sqrt(q) / xi) for q in qs))
    if kind == 'gauss':
        return sum(math.exp(-q / (xi * xi)) for q in qs)
    raise ValueError(kind)


def invariants(a, k, b):
    g = gram(a, k, b); t = modulus(a, k, b)
    q3 = g[0] + g[2] - g[1]
    return dict(gram=g, Q1=g[0], Q2=g[2], Q3=q3, tau=t, F=F_boson(a, k, b), n=a * b, A=3 * a * b)


def selftest():
    import csv, os
    here = os.path.dirname(os.path.abspath(__file__))
    ok = True
    for A in (48, 60, 72):
        with open(os.path.join(here, '..', 'shape2', 'data', f'classes_A{A}.csv')) as f:
            for r in csv.DictReader(f):
                a, k, b = int(r['cls_a']), int(r['cls_k']), int(r['cls_b'])
                g = gram(a, k, b)
                loops = [int(x) for x in r['loops6'].split()]
                # the first six primitive vectors up to sign: compare the two successive minima
                mine = (g[0], g[2])
                theirs = (int(r['l1']), int(r['l2']))
                # determinant check: Q1*Q2 - B^2 = 3 n^2 / 4
                det = g[0] * g[2] - g[1] ** 2 / 4
                good = mine == theirs and abs(det - 0.75 * (a * b) ** 2) < 1e-9
                # all vectors: smallest Q equals Q1, and counts are even
                qs = vectors(a, k, b, 4.0 * g[2])
                good = good and qs[0] == g[0] and len(qs) % 2 == 0
                # modular invariance of F under a change of basis
                t = modulus(a, k, b)
                f1 = -0.5 * math.log(t.imag) - 2 * math.log(eta_abs(t))
                t2 = -1 / (t + 1)
                f2 = -0.5 * math.log(t2.imag) - 2 * math.log(eta_abs(t2))
                good = good and abs(f1 - f2) < 1e-9
                ok = ok and good
                if not good:
                    print('MISMATCH', A, (a, k, b), mine, theirs, det, f1, f2)
    print('lat.py selftest:', 'ALL OK' if ok else 'FAILED')
    return ok


if __name__ == '__main__':
    if sys.argv[1] == 'selftest':
        sys.exit(0 if selftest() else 1)
    a, k, b = map(int, sys.argv[1:4])
    inv = invariants(a, k, b)
    print(inv)
    for xi in (0.7, 1.0, 1.5):
        print('xi', xi, 'exp', loop_sum(a, k, b, xi), 'k0', loop_sum(a, k, b, xi, 'k0'))
